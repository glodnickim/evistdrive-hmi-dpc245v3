#ifndef CAN_ROUTER_H
#define CAN_ROUTER_H

#include "bafang_can.h"
#include "bafang_service.h"
#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#define EVIST_CAN_LOG_CAPACITY 64u

typedef enum {
    EVIST_TX_READONLY = 0, /* service queries only */
    EVIST_TX_NORMAL_HMI,   /* + normal cyclic HMI frames */
    EVIST_TX_EXPERT        /* raw/write traffic permitted by explicit caller */
} evist_tx_mode_t;

typedef struct {
    bafang_can_frame_t frame;
    uint32_t sequence;
    bafang_frame_kind_t kind;
} evist_can_log_entry_t;

typedef struct {
    bafang_telemetry_t telemetry;
    bafang_service_rx_t service_rx;
    bafang_device_identity_t controller_identity;
    bafang_device_identity_t sensor_identity;
    bafang_device_identity_t battery_identity;
    bafang_battery_service_info_t battery_service;
    bafang_service_message_t last_service;
    bool have_last_service;   /* a message was ever completed (ACK bookkeeping) */
    bool service_event;       /* last_service was completed by the latest RX frame */
    bafang_can_frame_t service_ack_queue[8];
    uint8_t service_ack_head;
    uint8_t service_ack_count;
    evist_can_log_entry_t log[EVIST_CAN_LOG_CAPACITY];
    uint32_t rx_sequence;
    size_t log_head;
    size_t log_count;
    evist_tx_mode_t tx_mode;
} evist_can_router_t;

void evist_can_router_init(evist_can_router_t *r);
void evist_can_router_rx(evist_can_router_t *r, const bafang_can_frame_t *f, uint32_t now_ms);
const evist_can_log_entry_t *evist_can_router_log_newest(const evist_can_router_t *r,
                                                         size_t index_from_newest);
bool evist_can_router_tx_allowed(const evist_can_router_t *r,
                                 const bafang_can_frame_t *f,
                                 bool caller_marks_as_write);

/* Return one pending protocol ACK generated by a received multiframe service
 * transfer. Pure service parsing always happens even when target TX is disabled. */
bool evist_can_router_take_service_ack(evist_can_router_t *r,
                                       bafang_can_frame_t *out);
bool evist_can_router_peek_service_ack(const evist_can_router_t *r,
                                       bafang_can_frame_t *out);
void evist_can_router_pop_service_ack(evist_can_router_t *r);

#endif
