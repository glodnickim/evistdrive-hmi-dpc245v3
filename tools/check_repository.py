"""Validate repository contents before a build or release.

Checks that the documented files exist, that no build output or private file is
committed, that text files contain no local paths, no links leaving the
repository and no addresses outside the application memory map, that lines have
no trailing whitespace and that source files carry an SPDX licence header.
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
REQUIRED = [
    'README.md', 'LICENSE', 'NOTICE', 'CONTRIBUTING.md', 'CHANGELOG.md',
    'Makefile', '.gitignore', '.gitattributes', '.github/workflows/ci.yml',
    'docs/BUILDING.md', 'docs/ARCHITECTURE.md', 'docs/HARDWARE.md',
    'docs/CAN_PROTOCOL.md', 'docs/BLE_PROTOCOL.md', 'docs/UI.md',
    'docs/PERSISTENCE.md', 'docs/BUILD_AND_RELEASE.md', 'docs/DEVELOPMENT.md',
    'docs/TECHNICAL_REQUIREMENTS.md', 'docs/FUNCTION_REFERENCE.md',
    'docs/PINOUT.md', 'docs/INPUT_AND_POWER.md', 'docs/SCHEDULER.md',
    'docs/RTC.md', 'docs/FEATURE_COVERAGE.md',
    'tools/fonts/Inter-OFL-LICENSE.txt',
]
IMAGES = [
    'standard_dashboard', 'yellow_dashboard', 'arc_dashboard', 'wedge_dashboard',
    'main_menu', 'themes_page', 'temp_view_limits', 'overheat_warning',
    'advanced_assist', 'assist_modes',
]
# Generated locally, never part of the repository; skipped by the scan.
OUTPUT_DIRS = {'.git', 'build', 'dist', 'out'}
BAD_DIRS = {'private', '__pycache__', '.tmp'}
BAD_SUFFIXES = {'.bin', '.elf', '.map', '.pdf', '.jpg', '.jpeg', '.pyc', '.hex'}
TEXT_SUFFIXES = {'.c', '.h', '.py', '.ps1', '.md', '.txt', '.yml', '.yaml', '.ld', '.json', '.mk'}
TEXT_NAMES = {'Makefile', '.gitignore', '.gitattributes', 'NOTICE', 'LICENSE'}
SPDX_SUFFIXES = {'.c', '.h', '.py', '.ps1', '.ld', '.mk'}
SPDX_NAMES = {'Makefile'}
SPDX = 'SPDX-License-Identifier: GPL-3.0-or-later'
FONT_DATA_SPDX = 'SPDX-License-Identifier: OFL-1.1'
FONT_DATA_NAME = re.compile(r'ui_font1_[A-Za-z0-9_]+_data\.h\Z')
FONT_DATA_MARKER = 'Auto-generated by tools/gen_font1.ps1 - DO NOT EDIT.'

LOCAL_PATH = re.compile(r'(?i)(?:\b[A-Z]:\\|/mnt/[a-z]/|/home/[A-Za-z0-9_.-]+|[\\/]Users[\\/][A-Za-z0-9_.-]+)')
MD_LINK = re.compile(r'\]\(([^)\s]+)\)')
# Flash outside the application map, and RAM other than the window bounds.
FLASH_ADDR = re.compile(r'\b0x080[123][0-9A-Fa-f]{4}\b')
FLASH_ALLOWED = {'0x0803FFFD', '0x0803FFFE', '0x0803FFFF'}
RAM_ADDR = re.compile(r'\b0x2000[0-9A-Fa-f]{4}\b')
RAM_ALLOWED = {'0x20000000'}

# Display targets: shared code stays free of per-display values and conditions.
BOARD_MACROS = ['EVIST_BOARD_ID_HW', 'EVIST_BOARD_ID_SW', 'EVIST_BOARD_ID_MODEL',
                'EVIST_BOARD_RADIO_NAME_CMD', 'EVIST_BOARD_BLE_BAUD', 'EVIST_BOARD_BLE_BRR_PLL',
                'EVIST_BOARD_BLE_BRR_HSI', 'EVIST_BOARD_SPI_JEDEC_0', 'EVIST_BOARD_SPI_JEDEC_1',
                'EVIST_BOARD_SPI_JEDEC_2']
# Pattern checks, not a proof: identity strings, the radio name command, a
# literal UART divider, and conditions on target symbols. Target symbols are
# EVIST_BOARD_*, EVIST_TARGET*, BOARD_*, TARGET_* and display names such as DPC245_V3.
BOARD_VALUE = re.compile(r'"DP C\d{3}\b|"DPC\d{3}CF|"AT\+|ble_uart_init_brr\s*\(\s*[0-9]')
BOARD_CONDITION = re.compile(r'^\s*#\s*(?:if|ifdef|ifndef|elif)\b.*'
                             r'\b(?:EVIST_BOARD_\w*|EVIST_TARGET\w*|BOARD_\w+|TARGET_\w+|DPC\d+_V\d+)\b')
SHARED_DIRS = ('src', 'include', 'platform')


def strip_comments(text):
    """Blank C comments, keeping string and character literals and line numbers."""
    out = []
    index = 0
    quote = None
    while index < len(text):
        char = text[index]
        pair = text[index:index + 2]
        if quote:
            out.append(char)
            if char == '\\' and index + 1 < len(text):
                out.append(text[index + 1])
                index += 2
                continue
            if char == quote or char == '\n':
                quote = None
            index += 1
        elif pair == '/*':
            end = text.find('*/', index + 2)
            end = len(text) if end < 0 else end + 2
            out.append(re.sub(r'[^\n]', ' ', text[index:end]))
            index = end
        elif pair == '//':
            end = text.find('\n', index)
            end = len(text) if end < 0 else end
            out.append(' ' * (end - index))
            index = end
        else:
            if char in '"\'':
                quote = char
            out.append(char)
            index += 1
    return ''.join(out)


def board_findings(text):
    """Return (line, kind) findings in C text, ignoring comments."""
    code = strip_comments(text)
    found = [(code.count('\n', 0, match.start()) + 1, 'value')
             for match in BOARD_VALUE.finditer(code)]
    # Join continued directives; a joined line keeps its first line number.
    lines = code.splitlines()
    index = 0
    while index < len(lines):
        start = index
        joined = lines[index]
        while joined.rstrip().endswith('\\') and index + 1 < len(lines):
            index += 1
            joined = joined.rstrip()[:-1] + ' ' + lines[index]
        if BOARD_CONDITION.search(joined):
            found.append((start + 1, 'condition'))
        index += 1
    return found


BOARD_RULE_CASES = [
    ('static const char a[] = "DP C245.C 2.0";', ['value']),
    ('static const char a[] = "DPC244CF80271.3";', ['value']),
    ('static const char a[] = "DP C310.CAN";', ['value']),
    ('const char c[] = "AT+NAMEX\\r\\n";', ['value']),
    ('ble_uart_init_brr( 0x209u);', ['value']),
    ('ble_uart_init_brr(35u);', ['value']),
    ('ble_uart_init_brr(\n    0x209u);', ['value']),
    ('ble_uart_init_brr(\n    35u);', ['value']),
    ('ble_uart_init_brr(\n    EVIST_BOARD_BLE_BRR_HSI);', []),
    ('const char u[] = "/*";\n#if defined(EVIST_TARGET_V2)\n#endif /* end */', ['condition']),
    ('const char u[] = "*/"; ble_uart_init_brr(0x209u);', ['value']),
    ('const char u[] = "http://x"; const char v[] = "DP C245.CAN";', ['value']),
    ('const char u[] = "a\\"/*"; const char v[] = "DPC245CF80301.2";', ['value']),
    ("char q = '\"'; /* \"DP C245.C 3.0\" */", []),
    ('#if defined(DPC245_V3)', ['condition']),
    ('#ifdef EVIST_TARGET_V2', ['condition']),
    ('#if BOARD_HAS_RTC', ['condition']),
    ('#if 1 && \\\n    TARGET_V2', ['condition']),
    ('/* "AT+NAME" and "DP C245.C 3.0" */', []),
    ('#if 1 /* EVIST_BOARD_X */', []),
    ('ble_uart_init_brr(EVIST_BOARD_BLE_BRR_PLL);', []),
    ('m_text(84u,128u,"DPC245",DIM,BLACK,1u);', []),
    ('#ifndef DPC245_V3_PROFILE_H', []),
]

errors = []
for sample, expected in BOARD_RULE_CASES:
    if [kind for _, kind in board_findings(sample)] != expected:
        errors.append(f'board rule self-test failed: {sample!r}')
for name in REQUIRED:
    if not (ROOT / name).is_file():
        errors.append(f'missing {name}')
for name in IMAGES:
    if not (ROOT / 'docs/images' / (name + '.png')).is_file():
        errors.append(f'missing docs/images/{name}.png')


def check_links(rel, number, line):
    for target in MD_LINK.findall(line):
        if re.match(r'(?i)(?:https?:|mailto:|#)', target):
            continue
        path = target.split('#', 1)[0]
        if not path:
            continue
        resolved = (ROOT / rel).parent.joinpath(path).resolve()
        try:
            resolved.relative_to(ROOT)
        except ValueError:
            errors.append(f'{rel}:{number}: link leaves the repository: {target}')
            continue
        if not resolved.exists():
            errors.append(f'{rel}:{number}: link target missing: {target}')


for path in sorted(ROOT.rglob('*')):
    rel = path.relative_to(ROOT)
    if any(part in OUTPUT_DIRS for part in rel.parts):
        continue
    if any(part in BAD_DIRS for part in rel.parts):
        errors.append(f'private or generated path: {rel.as_posix()}')
        continue
    if not path.is_file():
        continue
    if path.suffix.lower() in BAD_SUFFIXES:
        errors.append(f'build output or binary document: {rel.as_posix()}')
        continue
    if path.suffix.lower() not in TEXT_SUFFIXES and path.name not in TEXT_NAMES:
        continue
    try:
        data = path.read_text(encoding='utf-8')
    except UnicodeError:
        errors.append(f'non-UTF-8 text: {rel.as_posix()}')
        continue
    if path.suffix.lower() in SPDX_SUFFIXES or path.name in SPDX_NAMES:
        expected_spdx = (FONT_DATA_SPDX if rel.parent == Path('include') and
                         FONT_DATA_NAME.fullmatch(path.name) and
                         FONT_DATA_MARKER in '\n'.join(data.splitlines()[:5]) else SPDX)
        if expected_spdx not in '\n'.join(data.splitlines()[:3]):
            errors.append(f'{rel.as_posix()}: missing "{expected_spdx}" in the first lines')
    for number, line in enumerate(data.splitlines(), 1):
        m = LOCAL_PATH.search(line)
        if m:
            errors.append(f'{rel.as_posix()}:{number}: local path: {m.group(0)}')
        if path.suffix.lower() == '.md':
            check_links(rel, number, line)
        for m in FLASH_ADDR.finditer(line):
            if m.group(0).upper().replace('0X', '0x') not in FLASH_ALLOWED:
                errors.append(f'{rel.as_posix()}:{number}: address outside the application map: {m.group(0)}')
        for m in RAM_ADDR.finditer(line):
            if m.group(0) not in RAM_ALLOWED:
                errors.append(f'{rel.as_posix()}:{number}: RAM address inside the window: {m.group(0)}')
        if line.rstrip() != line:
            errors.append(f'{rel.as_posix()}:{number}: trailing whitespace')

boards = sorted(p for p in (ROOT / 'boards').iterdir() if p.is_dir())
if not boards:
    errors.append('no display target in boards/')
for board in boards:
    if not (board / 'board.mk').is_file():
        errors.append(f'missing boards/{board.name}/board.mk')
    config = board / 'board_config.h'
    text = config.read_text(encoding='utf-8') if config.is_file() else ''
    for macro in BOARD_MACROS:
        if not re.search(rf'^#define {macro}\b', text, re.M):
            errors.append(f'boards/{board.name}/board_config.h: missing {macro}')
for folder in SHARED_DIRS:
    for path in sorted((ROOT / folder).rglob('*')):
        if path.suffix not in ('.c', '.h'):
            continue
        rel = path.relative_to(ROOT).as_posix()
        for number, kind in board_findings(path.read_text(encoding='utf-8')):
            errors.append(f'{rel}:{number}: per-display {kind} in shared code')

if errors:
    print('repository-check: FAIL')
    for error in errors:
        print(' - ' + error)
    sys.exit(1)
print('repository-check: PASS')
