"""Validate repository contents before a build or release.

Checks that the documented files exist, that no build output or private file is
committed, that text files contain no local paths, no links leaving the
repository and no addresses outside the application memory map, that lines have
no trailing whitespace and that source files carry an SPDX licence header.
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
REQUIRED = [
    'README.md', 'LICENSE', 'NOTICE', 'CONTRIBUTING.md', 'CHANGELOG.md',
    'Makefile', '.gitignore', '.gitattributes', '.github/workflows/ci.yml',
    'docs/BUILDING.md', 'docs/ARCHITECTURE.md', 'docs/HARDWARE.md',
    'docs/CAN_PROTOCOL.md', 'docs/BLE_PROTOCOL.md', 'docs/UI.md',
    'docs/PERSISTENCE.md', 'docs/BUILD_AND_RELEASE.md', 'docs/DEVELOPMENT.md',
    'docs/TECHNICAL_REQUIREMENTS.md', 'docs/FUNCTION_REFERENCE.md',
    'docs/PINOUT.md', 'docs/INPUT_AND_POWER.md', 'docs/SCHEDULER.md',
    'docs/RTC.md', 'docs/FEATURE_COVERAGE.md',
    'tools/fonts/Inter-OFL-LICENSE.txt',
]
IMAGES = [
    'standard_dashboard', 'yellow_dashboard', 'arc_dashboard', 'wedge_dashboard',
    'main_menu', 'themes_page', 'temp_view_limits', 'overheat_warning',
    'advanced_assist',
]
# Generated locally, never part of the repository; skipped by the scan.
OUTPUT_DIRS = {'.git', 'build', 'dist', 'out'}
BAD_DIRS = {'private', '__pycache__', '.tmp'}
BAD_SUFFIXES = {'.bin', '.elf', '.map', '.pdf', '.jpg', '.jpeg', '.pyc', '.hex'}
TEXT_SUFFIXES = {'.c', '.h', '.py', '.ps1', '.md', '.txt', '.yml', '.yaml', '.ld', '.json'}
TEXT_NAMES = {'Makefile', '.gitignore', '.gitattributes', 'NOTICE', 'LICENSE'}
SPDX_SUFFIXES = {'.c', '.h', '.py', '.ps1', '.ld'}
SPDX_NAMES = {'Makefile'}
SPDX = 'SPDX-License-Identifier: GPL-3.0-or-later'
FONT_DATA_SPDX = 'SPDX-License-Identifier: OFL-1.1'
FONT_DATA_NAME = re.compile(r'ui_font1_[A-Za-z0-9_]+_data\.h\Z')
FONT_DATA_MARKER = 'Auto-generated by tools/gen_font1.ps1 - DO NOT EDIT.'

LOCAL_PATH = re.compile(r'(?i)(?:\b[A-Z]:\\|/mnt/[a-z]/|/home/[A-Za-z0-9_.-]+|[\\/]Users[\\/][A-Za-z0-9_.-]+)')
MD_LINK = re.compile(r'\]\(([^)\s]+)\)')
# Flash outside the application map, and RAM other than the window bounds.
FLASH_ADDR = re.compile(r'\b0x080[123][0-9A-Fa-f]{4}\b')
FLASH_ALLOWED = {'0x0803FFFD', '0x0803FFFE', '0x0803FFFF'}
RAM_ADDR = re.compile(r'\b0x2000[0-9A-Fa-f]{4}\b')
RAM_ALLOWED = {'0x20000000'}

errors = []
for name in REQUIRED:
    if not (ROOT / name).is_file():
        errors.append(f'missing {name}')
for name in IMAGES:
    if not (ROOT / 'docs/images' / (name + '.png')).is_file():
        errors.append(f'missing docs/images/{name}.png')


def check_links(rel, number, line):
    for target in MD_LINK.findall(line):
        if re.match(r'(?i)(?:https?:|mailto:|#)', target):
            continue
        path = target.split('#', 1)[0]
        if not path:
            continue
        resolved = (ROOT / rel).parent.joinpath(path).resolve()
        try:
            resolved.relative_to(ROOT)
        except ValueError:
            errors.append(f'{rel}:{number}: link leaves the repository: {target}')
            continue
        if not resolved.exists():
            errors.append(f'{rel}:{number}: link target missing: {target}')


for path in sorted(ROOT.rglob('*')):
    rel = path.relative_to(ROOT)
    if any(part in OUTPUT_DIRS for part in rel.parts):
        continue
    if any(part in BAD_DIRS for part in rel.parts):
        errors.append(f'private or generated path: {rel.as_posix()}')
        continue
    if not path.is_file():
        continue
    if path.suffix.lower() in BAD_SUFFIXES:
        errors.append(f'build output or binary document: {rel.as_posix()}')
        continue
    if path.suffix.lower() not in TEXT_SUFFIXES and path.name not in TEXT_NAMES:
        continue
    try:
        data = path.read_text(encoding='utf-8')
    except UnicodeError:
        errors.append(f'non-UTF-8 text: {rel.as_posix()}')
        continue
    if path.suffix.lower() in SPDX_SUFFIXES or path.name in SPDX_NAMES:
        expected_spdx = (FONT_DATA_SPDX if rel.parent == Path('include') and
                         FONT_DATA_NAME.fullmatch(path.name) and
                         FONT_DATA_MARKER in '\n'.join(data.splitlines()[:5]) else SPDX)
        if expected_spdx not in '\n'.join(data.splitlines()[:3]):
            errors.append(f'{rel.as_posix()}: missing "{expected_spdx}" in the first lines')
    for number, line in enumerate(data.splitlines(), 1):
        m = LOCAL_PATH.search(line)
        if m:
            errors.append(f'{rel.as_posix()}:{number}: local path: {m.group(0)}')
        if path.suffix.lower() == '.md':
            check_links(rel, number, line)
        for m in FLASH_ADDR.finditer(line):
            if m.group(0).upper().replace('0X', '0x') not in FLASH_ALLOWED:
                errors.append(f'{rel.as_posix()}:{number}: address outside the application map: {m.group(0)}')
        for m in RAM_ADDR.finditer(line):
            if m.group(0) not in RAM_ALLOWED:
                errors.append(f'{rel.as_posix()}:{number}: RAM address inside the window: {m.group(0)}')
        if line.rstrip() != line:
            errors.append(f'{rel.as_posix()}:{number}: trailing whitespace')

if errors:
    print('repository-check: FAIL')
    for error in errors:
        print(' - ' + error)
    sys.exit(1)
print('repository-check: PASS')
