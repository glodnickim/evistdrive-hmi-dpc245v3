# gen_font1.ps1 - generates a crisp 1-bit subset font (ui_font1_t) for EVistDrive HMI.
#
# Requires Windows PowerShell with .NET System.Drawing (GDI+); it does not run
# on Linux. The generated headers are committed, so a normal build never runs it.
#
# Example (main speed digits, include/ui_font1_speed_data.h):
#   powershell -ExecutionPolicy Bypass -File tools/gen_font1.ps1 `
#     -Em 130 -Chars "0123456789" -Name ui_font1_speed -Out include/ui_font1_speed_data.h
#
# Format: only the characters of -Chars, rendered without smoothing; every glyph
# has its own width and advance. ui_font1_glyph_t {w,h,ox,oy,adv,off}, ox/oy
# relative to (pen, baseline). Rows are packed MSB first, ceil(w/8) bytes per row.

param(
    [string]$Ttf   = "$PSScriptRoot\fonts\InterDisplay-Bold.ttf",
    [double]$Em    = 18.0,
    [Parameter(Mandatory = $true)][string]$Chars,
    [Parameter(Mandatory = $true)][string]$Name,
    [Parameter(Mandatory = $true)][string]$Out,
    # Extra pixels added to every advance (letter spacing).
    [int]$Track    = 0
)

Add-Type -AssemblyName System.Drawing
$pfc = New-Object System.Drawing.Text.PrivateFontCollection
$pfc.AddFontFile($Ttf)
$family = $pfc.Families[0]
$style  = [System.Drawing.FontStyle]::Bold
$font   = New-Object System.Drawing.Font($family, $Em, $style, [System.Drawing.GraphicsUnit]::Pixel)

$emHeight = $family.GetEmHeight($style)
$ascentPx = [Math]::Round($family.GetCellAscent($style) * $Em / $emHeight)

$sf = [System.Drawing.StringFormat]::GenericTypographic
$sf.FormatFlags = $sf.FormatFlags -bor [System.Drawing.StringFormatFlags]::NoClip -bor [System.Drawing.StringFormatFlags]::MeasureTrailingSpaces

$size = [int][Math]::Ceiling($Em * 1.6) + 16
$pen  = [double]([int][Math]::Ceiling($Em * 0.25) + 4)
$top  = 4.0
$base = [int]$top + $ascentPx
$glyphs = @(); $pool = New-Object System.Collections.Generic.List[byte]
foreach ($ch in $Chars.ToCharArray()) {
    $bmp = New-Object System.Drawing.Bitmap($size, $size)
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $g.Clear([System.Drawing.Color]::White)
    $g.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::SingleBitPerPixelGridFit
    $g.DrawString([string]$ch, $font, [System.Drawing.Brushes]::Black, $pen, $top, $sf)
    $adv = [int][Math]::Round($g.MeasureString([string]$ch, $font, 1000, $sf).Width)
    $g.Dispose()
    $minx=9999; $miny=9999; $maxx=-1; $maxy=-1
    for ($y=0; $y -lt $size; $y++) { for ($x=0; $x -lt $size; $x++) {
        if ($bmp.GetPixel($x,$y).R -lt 128) {
            if ($x -lt $minx){$minx=$x}; if ($x -gt $maxx){$maxx=$x}
            if ($y -lt $miny){$miny=$y}; if ($y -gt $maxy){$maxy=$y} } } }
    $w=0; $h=0; $ox=0; $oy=0; $off=$pool.Count
    if ($maxx -ge 0) {
        $w = $maxx - $minx + 1; $h = $maxy - $miny + 1
        $ox = $minx - [int]$pen; $oy = $miny - $base
        $rb = [int][Math]::Floor(($w + 7) / 8)
        for ($y=$miny; $y -le $maxy; $y++) { for ($b=0; $b -lt $rb; $b++) {
            $v = 0
            for ($k=0; $k -lt 8; $k++) { $x = $minx + 8*$b + $k
                if ($x -le $maxx -and $bmp.GetPixel($x,$y).R -lt 128) { $v = $v -bor (0x80 -shr $k) } }
            $pool.Add([byte]$v) } }
    }
    $bmp.Dispose()
    if ($adv -lt 1) { $adv = 1 }
    $adv += $Track
    $glyphs += [pscustomobject]@{ c=$ch; w=$w; h=$h; ox=$ox; oy=$oy; adv=$adv; off=$off }
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("/* SPDX-License-Identifier: OFL-1.1 */")
[void]$sb.AppendLine("/* Auto-generated by tools/gen_font1.ps1 - DO NOT EDIT.")
[void]$sb.AppendLine(" * Source: $(Split-Path -Leaf $Ttf), em=$Em px, track=$Track px, 1 bpp, rows MSB first, ceil(w/8) B per row.")
[void]$sb.AppendLine(" * ox/oy relative to (pen, baseline). */")
[void]$sb.AppendLine("#include `"ui_font1.h`"")
[void]$sb.AppendLine("static const char ${Name}_codes[] = `"$Chars`";")
[void]$sb.AppendLine("static const ui_font1_glyph_t ${Name}_glyphs[] = {")
foreach ($gl in $glyphs) { [void]$sb.AppendLine("  { $($gl.w),$($gl.h),$($gl.ox),$($gl.oy),$($gl.adv),$($gl.off) }, /* '$($gl.c)' */") }
[void]$sb.AppendLine("};")
[void]$sb.AppendLine("static const uint8_t ${Name}_bitmap[] = {")
for ($i=0; $i -lt $pool.Count; $i+=16) {
    $n = [Math]::Min(16, $pool.Count - $i); $chunk = @()
    for ($j=0; $j -lt $n; $j++) { $chunk += ("0x{0:X2}" -f $pool[$i+$j]) }
    [void]$sb.AppendLine("  " + ($chunk -join ",") + ",") }
[void]$sb.AppendLine("};")
[void]$sb.AppendLine("const ui_font1_t $Name = { ${Name}_codes, ${Name}_glyphs, ${Name}_bitmap, $($glyphs.Count) };")
$sb.Replace("`r`n", "`n") | Out-Null
[System.IO.File]::WriteAllText((Resolve-Path -LiteralPath (Split-Path -Parent $Out)).Path + "\" + (Split-Path -Leaf $Out), $sb.ToString())
Write-Output ("written: " + $Out + "  glyphs=" + $glyphs.Count + "  bitmap=" + $pool.Count + " B")
